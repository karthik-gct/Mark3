#!/usr/bin/env bash
# Mark3 Setup Script
# Configures Mark3 for a new machine or user.
# Run once after cloning: bash setup.sh

set -euo pipefail

MARK3_ROOT="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="$MARK3_ROOT/.env"
SETTINGS_TEMPLATE="$MARK3_ROOT/.claude/settings.template.json"
SETTINGS_OUT="$MARK3_ROOT/.claude/settings.json"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
ok()   { echo -e "${GREEN}✓${NC} $*"; }
warn() { echo -e "${YELLOW}!${NC} $*"; }
fail() { echo -e "${RED}✗${NC} $*"; }
ask()  { local var="$1" prompt="$2" default="${3:-}"; printf "%s" "$prompt"; [ -n "$default" ] && printf " [%s]" "$default"; printf ": "; read -r val; val="${val:-$default}"; eval "$var=\"$val\""; }

echo ""
echo "╔══════════════════════════════════════════════════════╗"
echo "║      Mark3 — Autonomous SDLC Scaffolding Setup       ║"
echo "╚══════════════════════════════════════════════════════╝"
echo ""
echo "This script will:"
echo "  1. Create your .env file from .env.example"
echo "  2. Generate .claude/settings.json"
echo "  3. Validate Jira connection"
echo "  4. Check element35-mcp is available"
echo ""

# ── Step 1: Load existing .env or create from example ────────────────────────
if [ -f "$ENV_FILE" ]; then
  warn ".env already exists. Loading existing values as defaults."
  set -a; source "$ENV_FILE"; set +a
else
  cp "$MARK3_ROOT/.env.example" "$ENV_FILE"
  ok "Created .env from .env.example"
fi

echo ""
echo "── Atlassian Jira ───────────────────────────────────────"
ask ATLASSIAN_BASE_URL  "  Atlassian Cloud URL (no trailing slash)" "${ATLASSIAN_BASE_URL:-https://your-org.atlassian.net}"
ask ATLASSIAN_EMAIL     "  Atlassian email"                          "${ATLASSIAN_EMAIL:-}"
ask ATLASSIAN_API_TOKEN "  Atlassian API token"                      "${ATLASSIAN_API_TOKEN:-}"
ask JIRA_PROJECT_KEY    "  Jira project key (e.g. SCRUM)"           "${JIRA_PROJECT_KEY:-SCRUM}"

echo ""
echo "── Anthropic API ────────────────────────────────────────"
ask ANTHROPIC_API_KEY   "  Anthropic API key"                        "${ANTHROPIC_API_KEY:-}"

echo ""
echo "── Context Graph (element35-mcp) ────────────────────────"
DEFAULT_E35="${ELEMENT35_MCP_ROOT:-}"
if [ -z "$DEFAULT_E35" ]; then
  # Try to auto-detect in common sibling paths
  for candidate in \
    "$(dirname "$MARK3_ROOT")/AIHarness_Mark1/context-graph-rag/element35-mcp" \
    "$HOME/CodingOcean/AIHarness_Mark1/context-graph-rag/element35-mcp"; do
    if [ -d "$candidate" ]; then DEFAULT_E35="$candidate"; break; fi
  done
fi
ask ELEMENT35_MCP_ROOT "  Path to element35-mcp directory" "${DEFAULT_E35}"

echo ""
echo "── STARK Router (optional — press Enter to skip) ────────"
ask STARK_ROOT     "  Path to STARK directory" "${STARK_ROOT:-}"
ask STARK_ENDPOINT "  STARK endpoint"          "${STARK_ENDPOINT:-http://localhost:8000}"

echo ""
echo "── Google Gemini (optional — used for embeddings) ───────"
ask GOOGLE_API_KEY "  Google API key" "${GOOGLE_API_KEY:-}"

# ── Write .env ────────────────────────────────────────────────────────────────
cat > "$ENV_FILE" <<EOF
# Mark3 Environment — generated by setup.sh
# Do not commit this file.

ATLASSIAN_BASE_URL=$ATLASSIAN_BASE_URL
ATLASSIAN_EMAIL=$ATLASSIAN_EMAIL
ATLASSIAN_API_TOKEN=$ATLASSIAN_API_TOKEN
JIRA_PROJECT_KEY=$JIRA_PROJECT_KEY

ANTHROPIC_API_KEY=$ANTHROPIC_API_KEY

ELEMENT35_MCP_ROOT=$ELEMENT35_MCP_ROOT

STARK_ROOT=$STARK_ROOT
STARK_ENDPOINT=$STARK_ENDPOINT

GOOGLE_API_KEY=$GOOGLE_API_KEY
EOF
ok ".env written"

# ── Generate settings.json from template ──────────────────────────────────────
echo ""
echo "── Generating .claude/settings.json ────────────────────"
sed \
  -e "s|__ELEMENT35_MCP_ROOT__|$ELEMENT35_MCP_ROOT|g" \
  -e "s|__MARK3_ROOT__|$MARK3_ROOT|g" \
  "$SETTINGS_TEMPLATE" > "$SETTINGS_OUT"
ok "settings.json generated"

# ── Validate: Jira API ────────────────────────────────────────────────────────
echo ""
echo "── Validating Jira connection ───────────────────────────"
HTTP_STATUS=$(curl -s -o /tmp/jira_test.json -w "%{http_code}" \
  -u "${ATLASSIAN_EMAIL}:${ATLASSIAN_API_TOKEN}" \
  -H "Accept: application/json" \
  "${ATLASSIAN_BASE_URL}/rest/api/3/myself" 2>/dev/null || echo "000")

if [ "$HTTP_STATUS" = "200" ]; then
  DISPLAY_NAME=$(python3 -c "import json; d=json.load(open('/tmp/jira_test.json')); print(d.get('displayName','?'))" 2>/dev/null || echo "unknown")
  ok "Jira auth OK — logged in as: $DISPLAY_NAME"

  # List projects
  curl -s \
    -u "${ATLASSIAN_EMAIL}:${ATLASSIAN_API_TOKEN}" \
    -H "Accept: application/json" \
    "${ATLASSIAN_BASE_URL}/rest/api/3/project/search?maxResults=10" \
    | python3 -c "
import sys, json
d = json.load(sys.stdin)
projects = d.get('values', [])
print(f'  Projects available ({len(projects)}):')
for p in projects:
    print(f'    {p[\"key\"]:10} {p[\"name\"]}')
" 2>/dev/null || warn "Could not list projects"
elif [ "$HTTP_STATUS" = "401" ]; then
  fail "Jira auth FAILED (401) — check ATLASSIAN_EMAIL and ATLASSIAN_API_TOKEN"
else
  fail "Jira connection failed (HTTP $HTTP_STATUS) — check ATLASSIAN_BASE_URL"
fi

# ── Validate: element35-mcp ────────────────────────────────────────────────────
echo ""
echo "── Checking element35-mcp ───────────────────────────────"
if [ -d "$ELEMENT35_MCP_ROOT" ]; then
  if [ -f "$ELEMENT35_MCP_ROOT/package.json" ]; then
    ok "element35-mcp found at: $ELEMENT35_MCP_ROOT"
    if [ -d "$ELEMENT35_MCP_ROOT/node_modules" ]; then
      ok "node_modules present"
    else
      warn "node_modules missing — run: cd $ELEMENT35_MCP_ROOT && npm install"
    fi
  else
    warn "Directory exists but no package.json — check ELEMENT35_MCP_ROOT path"
  fi
else
  warn "element35-mcp not found at: $ELEMENT35_MCP_ROOT"
  warn "Agents will run without context graph (degraded mode)"
  warn "See context/graph_bootstrap_gap.md for setup instructions"
fi

# ── Validate: mcp-atlassian installed ─────────────────────────────────────────
echo ""
echo "── Checking mcp-atlassian ───────────────────────────────"
if npx -y mcp-atlassian --version 2>/dev/null | grep -q "atlassian\|[0-9]" || \
   ATLASSIAN_BASE_URL=x ATLASSIAN_EMAIL=x ATLASSIAN_API_TOKEN=x npx mcp-atlassian 2>&1 | grep -q "Missing\|ATLASSIAN"; then
  ok "mcp-atlassian available"
else
  warn "mcp-atlassian not yet cached — will be downloaded on first use (npx -y)"
fi

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo "╔══════════════════════════════════════════════════════╗"
echo "║                    Setup Complete                     ║"
echo "╚══════════════════════════════════════════════════════╝"
echo ""
echo "  Files written:"
echo "    .env                     (credentials — gitignored)"
echo "    .claude/settings.json    (generated from template)"
echo ""
echo "  Next steps:"
echo "    1. Fill in ArchitectureDesign.md with your project's tech stack"
echo "    2. Start element35-mcp: cd $ELEMENT35_MCP_ROOT && npm run mcp"
echo "    3. Open Claude Code in this directory"
echo "    4. Run /prod-agent <your-jira-concept-key>"
echo ""
echo "  Docs: Mark3-Overview.md"
echo ""
